// Array Methods 

// forEach 

let arr = [1, 2, 3, 4, 5, 6];

let print = function (el) {
    console.log(el);
}

arr.forEach(print);



let arrayEach = [10, 12, 14, 16, 18];

let printEach = function (each) {
    console.log(each);
}

arrayEach.forEach(printEach);

let singleArr = [99, 101, 41, 87, 27];

let printSingle = function (single) {
    console.log(single);
}

singleArr.forEach(single);
